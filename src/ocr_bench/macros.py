"""Render the consolidated results into the paper's LaTeX ``\\newcommand`` macros.

Every figure in the paper is driven by a macro in ``results_macros.tex``. This
module rebuilds the data-driven subset of those macros from the consolidated
results so the regenerated values can be checked, field by field, against the
committed reference the paper actually compiles. Number formatting mirrors the
paper: FVR/latency use Python's minimal float repr (``0.97``, not ``0.970``);
NED keeps its 2-dp source precision; absent cells render as ``--``.
"""
from __future__ import annotations

from typing import Any

from .config import ENGINES

# Engine key -> the paper's LaTeX macro tag (LaTeX names carry no digits).
TAG = {
    "paddleocrvl": "PaddleVL",
    "hunyuanocr": "Huny",
    "mineru": "Mineru",
    "deepseekocr": "DeepSeek",
    "dotsocr": "Dots",
    "qwen3vl": "QwenThree",
    "qwen25vl": "QwenTwoFive",
    "glmocr": "Glm",
    "tesseract": "Tess",
    "easyocr": "Easy",
    "doctr": "DocTR",
    "rapidocr": "Rapid",
    "paddleocr": "Paddle",
    "surya": "Surya",
}

DASH = "--"


def _fnum(x: float | None) -> str:
    """Minimal-float-repr of a number, or ``--`` for ``None`` (matches the paper).

    Rounds to 3 dp, the paper's print precision for FVR cells. NED cells arrive
    already rounded to 2 dp, so a 3-dp round is a no-op for them; FVR CI bounds
    carried at 4 dp collapse to the paper's 3-dp value (e.g. 0.8635 -> 0.864).
    """
    if x is None:
        return DASH
    return repr(round(x, 3))


def _cmd(name: str, value: str) -> str:
    return f"\\newcommand{{\\{name}}}{{{value}}}"


def build_macros(results: dict[str, dict[str, Any]]) -> dict[str, str]:
    """Map every data-driven macro name to its rendered value string."""
    m: dict[str, str] = {}
    for e in ENGINES:
        tag = TAG[e.key]
        r = results[e.key]
        m[f"p{tag}"] = e.params if e.params != "-" else "-"

        forms = r.get("forms")
        if forms:
            m[f"forms{tag}"] = _fnum(forms["fvr"])
            m[f"forms{tag}Lo"] = _fnum(forms["ci"][0])
            m[f"forms{tag}Hi"] = _fnum(forms["ci"][1])
            if e.type == "vlm":
                m[f"forms{tag}Excl"] = _fnum(forms["fvr_excl_degen"])

        ids = r.get("ids")
        m[f"ids{tag}"] = _fnum(ids["fvr"]) if ids else DASH
        if ids:
            m[f"ids{tag}Lo"] = _fnum(ids["ci"][0])
            m[f"ids{tag}Hi"] = _fnum(ids["ci"][1])

        if e.type == "vlm":
            en = r.get("en")
            m[f"en{tag}"] = _fnum(en["fvr"]) if en else DASH
            if en:
                m[f"en{tag}Lo"] = _fnum(en["ci"][0])
                m[f"en{tag}Hi"] = _fnum(en["ci"][1])

        rib = r.get("rib")
        m[f"rib{tag}"] = _fnum(rib["ned"]) if rib else DASH
        if rib:
            m[f"rib{tag}Lo"] = _fnum(rib["ci"][0])
            m[f"rib{tag}Hi"] = _fnum(rib["ci"][1])

        hyb = r.get("hyb")
        m[f"hyb{tag}"] = _fnum(hyb["ned"]) if hyb else DASH
        if hyb:
            m[f"hyb{tag}Lo"] = _fnum(hyb["ci"][0])
            m[f"hyb{tag}Hi"] = _fnum(hyb["ci"][1])

        lat = r.get("latency", {})
        if lat.get("forms_med") is not None or e.type != "classical":
            m[f"latF{tag}"] = _fnum(lat.get("forms_med"))
        if lat.get("ids_med") is not None or e.key not in {"mineru"}:
            m[f"latI{tag}"] = _fnum(lat.get("ids_med"))
    return m


# Per-engine macro name templates, in paper order; ``{tag}`` is substituted.
_ENGINE_MACRO_ORDER = (
    "p{tag}",
    "forms{tag}", "forms{tag}Lo", "forms{tag}Hi", "forms{tag}Excl",
    "ids{tag}", "ids{tag}Lo", "ids{tag}Hi",
    "en{tag}", "en{tag}Lo", "en{tag}Hi",
    "rib{tag}", "rib{tag}Lo", "rib{tag}Hi",
    "hyb{tag}", "hyb{tag}Lo", "hyb{tag}Hi",
    "latF{tag}", "latI{tag}",
)


# The IDs paired-bootstrap macros, in the order the paper lists them. Passed in
# from the bootstrap layer so this module stays free of the resampling logic.
_PAIR_MACRO_ORDER = (
    "idsPairSurya", "idsPairDeepSeek", "idsPairDiff", "idsPairLo", "idsPairHi",
)


def render_tex(results: dict[str, dict[str, Any]],
               pair_macros: dict[str, str] | None = None) -> str:
    """Render the data-driven macros as a ``results_macros.tex`` fragment.

    When ``pair_macros`` is supplied (the IDs paired document-level bootstrap),
    its macros are appended in a trailing block so the regenerated fragment
    carries the significance test alongside the per-engine cells.
    """
    m = build_macros(results)
    lines = [
        "% AUTO-GENERATED by ocr-bench from the committed run of record.",
        "% Data-driven subset of the paper's results_macros.tex (per-engine cells).",
    ]
    for e in ENGINES:
        tag = TAG[e.key]
        lines.append(f"% ----- {results[e.key]['display']} -----")
        for tmpl in _ENGINE_MACRO_ORDER:
            name = tmpl.format(tag=tag)
            if name in m:
                lines.append(_cmd(name, m[name]))
    if pair_macros:
        lines.append("% ----- IDs paired document-level bootstrap significance test -----")
        for name in _PAIR_MACRO_ORDER:
            if name in pair_macros:
                lines.append(_cmd(name, pair_macros[name]))
    return "\n".join(lines) + "\n"
